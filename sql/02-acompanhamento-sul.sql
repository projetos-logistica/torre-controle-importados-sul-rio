-- Executar no SSMS, substituindo CHAVE_NFE para testes.
DECLARE @CHAVE_NFE VARCHAR(44)='42260109611669001328550120000208761308221923';
;WITH AG AS (
 SELECT R.*, ROW_NUMBER() OVER (PARTITION BY R.CHAVE_NFE
  ORDER BY R.DATA_HORA_AGENDAMENTO DESC, R.DATA_FIM_RECEBIMENTO DESC) RN
 FROM LL_RECEBIMENTO_AGENDADO R WHERE R.CHAVE_NFE=@CHAVE_NFE
), EMB AS (
 SELECT I.CHAVE_NFE,C.ROMANEIO,C.TRANSPORTADORA,C.PLACA,C.MOTORISTA,C.DATA_EMBARQUE,
 ROW_NUMBER() OVER (PARTITION BY I.CHAVE_NFE ORDER BY
 CASE WHEN C.DATA_EMBARQUE IS NOT NULL THEN 0 ELSE 1 END,
 C.DATA_EMBARQUE DESC,C.DATA_HORA_CRIACAO DESC,C.ROMANEIO DESC) RN
 FROM SS_ROMANEIOS_CARGA_ITEM I JOIN SS_ROMANEIOS_CARGA C ON C.ROMANEIO=I.ROMANEIO
 WHERE I.CHAVE_NFE=@CHAVE_NFE AND LTRIM(RTRIM(C.TIPO_ROMANEIO))='SUL X RJ (IMPORTADO)'
)
SELECT @CHAVE_NFE CHAVE_NFE, AG.DATA_HORA_AGENDAMENTO DATA_AGENDAMENTO,
 AG.DATA_INICIO_RECEBIMENTO INICIO_CONFERENCIA_SUL,AG.DATA_FIM_RECEBIMENTO FIM_CONFERENCIA_SUL,
 CAST(EMB.ROMANEIO AS VARCHAR(30)) ROMANEIO,EMB.TRANSPORTADORA,EMB.PLACA,EMB.MOTORISTA,
 EMB.DATA_EMBARQUE,CASE WHEN EMB.DATA_EMBARQUE IS NOT NULL THEN DATEADD(DAY,2,CAST(EMB.DATA_EMBARQUE AS DATE)) END PREVISAO_CHEGADA
FROM (SELECT 1 AS X) B LEFT JOIN AG ON AG.RN=1 LEFT JOIN EMB ON EMB.RN=1;
