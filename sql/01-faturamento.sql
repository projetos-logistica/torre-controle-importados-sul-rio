-- Consulta ilustrativa para validar a origem de dados; ajustar filtros ao ambiente.
DECLARE @NF VARCHAR(20) = '000020876';
DECLARE @SERIE VARCHAR(10) = '12';
;WITH I AS (
  SELECT FP.FILIAL, FP.NF_SAIDA, FP.SERIE_NF,
         SUM(FP.QTDE) AS QUANTIDADE, SUM(FP.VALOR) AS VALOR,
         COUNT(DISTINCT LTRIM(RTRIM(LR.DESC_REDE_LOJAS))) AS TOTAL_MARCAS,
         MAX(LTRIM(RTRIM(LR.DESC_REDE_LOJAS))) AS MARCA
  FROM FATURAMENTO_PROD FP
  LEFT JOIN PRODUTOS P ON P.PRODUTO = FP.PRODUTO
  LEFT JOIN LOJAS_REDE LR ON LR.REDE_LOJAS = P.REDE_LOJAS
  WHERE FP.NF_SAIDA = @NF AND FP.SERIE_NF = @SERIE
  GROUP BY FP.FILIAL, FP.NF_SAIDA, FP.SERIE_NF
)
SELECT A.FILIAL, A.NF_SAIDA, A.SERIE_NF, A.CHAVE_NFE,
       CASE WHEN LTRIM(RTRIM(A.NOME_CLIFOR))='CONTROLE QUALIDADE ATAC' THEN 'ATACADO'
            WHEN LTRIM(RTRIM(A.NOME_CLIFOR))='CONTROLE QUALIDADE VAREJO' THEN 'VAREJO'
            ELSE LTRIM(RTRIM(A.NOME_CLIFOR)) END AS CANAL,
       CASE WHEN I.TOTAL_MARCAS>1 THEN 'MULTIMARCAS' ELSE I.MARCA END AS MARCA,
       I.QUANTIDADE, I.VALOR
FROM FATURAMENTO A JOIN I ON I.FILIAL=A.FILIAL AND I.NF_SAIDA=A.NF_SAIDA AND I.SERIE_NF=A.SERIE_NF
WHERE A.NF_SAIDA=@NF AND A.SERIE_NF=@SERIE AND A.CHAVE_NFE IS NOT NULL;
