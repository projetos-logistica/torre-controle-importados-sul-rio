DECLARE @CHAVE_NFE VARCHAR(44)='42260109611669001328550120000208761308221923';
SELECT TOP (1) E.CHAVE_NFE, E.FILIAL AS FILIAL_ENTRADA,
       CAST(E.DATA_DIGITACAO AS DATE) AS DATA_ENTRADA_FISCAL
FROM ENTRADAS E
WHERE E.CHAVE_NFE=@CHAVE_NFE AND ISNULL(E.NOTA_CANCELADA,0)=0
  AND E.DATA_DIGITACAO IS NOT NULL
ORDER BY E.DATA_DIGITACAO DESC,E.NUMERO_ENTRADA DESC;
